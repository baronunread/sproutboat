import { afterEach, beforeEach, describe, expect, test } from "bun:test";
import { chmod, mkdtemp, readdir, readFile, rm, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

// Operator settings must survive `sbctl update`. install.sh rewrites control.env, sproutboat.env,
// egress.env and caddy.env on every run; anything of the operator's lives in the matching
// <name>.local.env, which the units read last and nothing rewrites. infra/sb-envsplit moves
// settings found in an installer-owned file into the local one (a one-time migration).

let dir: string;
beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "sb-envsplit-"));
});
afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

const GENERATED = [
  "# Generated by install.sh",
  "SPROUTBOAT_BOOTSTRAP_TOKEN=abc123",
  "BETTER_AUTH_URL=https://dashboard.example.com",
  "",
].join("\n");
const OWNED = ["SPROUTBOAT_BOOTSTRAP_TOKEN", "BETTER_AUTH_URL"];

function split(managed: string, local: string, ...keys: string[]) {
  const r = Bun.spawnSync(["bash", "infra/sb-envsplit", managed, local, ...keys]);
  return { code: r.exitCode, out: r.stdout.toString(), err: r.stderr.toString() };
}

describe("sb-envsplit", () => {
  test("moves a key the installer does not own into the local file and keeps the rest", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(
      managed,
      GENERATED +
        "SPROUTBOAT_BACKUP_ENCRYPT=off\nSPROUTBOAT_BACKUP_S3_BUCKET=my-bucket\nSPROUTBOAT_MAX_PROJECTS_PER_ACCOUNT=200\n",
    );
    const r = split(managed, local, ...OWNED);
    expect(r.code).toBe(0);
    expect(r.out).toContain("moved SPROUTBOAT_BACKUP_ENCRYPT\n");
    expect(r.out).toContain("moved SPROUTBOAT_BACKUP_S3_BUCKET\n");
    expect(r.out).toContain("moved SPROUTBOAT_MAX_PROJECTS_PER_ACCOUNT\n");
    expect(await readFile(managed, "utf8")).toBe(GENERATED);
    const moved = await readFile(local, "utf8");
    expect(moved).toContain("SPROUTBOAT_BACKUP_ENCRYPT=off\n");
    expect(moved).toContain("SPROUTBOAT_BACKUP_S3_BUCKET=my-bucket\n");
    expect(moved).toContain("SPROUTBOAT_MAX_PROJECTS_PER_ACCOUNT=200\n");
    expect(moved).not.toContain("SPROUTBOAT_BOOTSTRAP_TOKEN");
  });

  test("keeps a copy of the old file, readable only by its owner", async () => {
    const managed = join(dir, "control.env");
    const old = GENERATED + "SPROUTBOAT_BACKUP_ENCRYPT=off\n";
    await writeFile(managed, old);
    const r = split(managed, join(dir, "control.local.env"), ...OWNED);
    const backup = /^backup (.+)$/m.exec(r.out)?.[1];
    expect(backup).toBeTruthy();
    expect(backup!.startsWith(`${managed}.bak-`)).toBe(true);
    expect(await readFile(backup!, "utf8")).toBe(old);
    expect((await stat(backup!)).mode & 0o777).toBe(0o600);
  });

  test("is idempotent: a second run finds nothing, writes no second backup and prints nothing", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(managed, GENERATED + "SPROUTBOAT_BACKUP_ENCRYPT=off\n");
    split(managed, local, ...OWNED);
    const again = split(managed, local, ...OWNED);
    expect(again.code).toBe(0);
    expect(again.out).toBe("");
    expect((await readdir(dir)).filter((f) => f.includes(".bak-"))).toHaveLength(1);
  });

  test("does nothing, and creates nothing, when the installer owns every key", async () => {
    const managed = join(dir, "control.env");
    await writeFile(managed, GENERATED);
    const r = split(managed, join(dir, "control.local.env"), ...OWNED);
    expect(r.code).toBe(0);
    expect(r.out).toBe("");
    expect(existsSync(join(dir, "control.local.env"))).toBe(false);
    expect(await readdir(dir)).toEqual(["control.env"]);
  });

  test("a managed file that does not exist is not an error (a fresh install)", () => {
    const r = split(join(dir, "control.env"), join(dir, "control.local.env"), ...OWNED);
    expect(r.code).toBe(0);
    expect(readdir(dir)).resolves.toEqual([]);
  });

  test("appends to a local file that exists and keeps what is in it", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(local, "# mine\nSPROUTBOAT_DEPLOY_RATE_PER_MIN=3"); // no trailing newline
    await writeFile(managed, GENERATED + "SPROUTBOAT_BACKUP_ENCRYPT=off\n");
    split(managed, local, ...OWNED);
    const text = await readFile(local, "utf8");
    expect(text.startsWith("# mine\nSPROUTBOAT_DEPLOY_RATE_PER_MIN=3\n")).toBe(true);
    expect(text).toContain("\nSPROUTBOAT_BACKUP_ENCRYPT=off\n");
  });

  test("a key the local file already sets keeps its local value; the managed copy is dropped and reported", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(local, "SPROUTBOAT_DEPLOY_RATE_PER_MIN=3\n");
    await writeFile(managed, GENERATED + "SPROUTBOAT_DEPLOY_RATE_PER_MIN=99\nSPROUTBOAT_BACKUP_ENCRYPT=off\n");
    const r = split(managed, local, ...OWNED);
    expect(r.out).toContain("kept SPROUTBOAT_DEPLOY_RATE_PER_MIN\n");
    expect(r.out).not.toContain("moved SPROUTBOAT_DEPLOY_RATE_PER_MIN");
    const text = await readFile(local, "utf8");
    expect(text).toContain("SPROUTBOAT_DEPLOY_RATE_PER_MIN=3\n");
    expect(text).not.toContain("=99");
    expect(await readFile(managed, "utf8")).toBe(GENERATED);
  });

  test("the same line already in the local file is dropped and reported as the same (a rollback, then another update)", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(local, "SPROUTBOAT_BACKUP_ENCRYPT=off\n");
    await writeFile(managed, GENERATED + "SPROUTBOAT_BACKUP_ENCRYPT=off\n");
    const r = split(managed, local, ...OWNED);
    expect(r.code).toBe(0);
    expect(r.out).toContain("same SPROUTBOAT_BACKUP_ENCRYPT\n");
    expect(r.out).not.toContain("kept");
    expect(r.out).not.toContain("moved");
    expect(await readFile(local, "utf8")).toBe("SPROUTBOAT_BACKUP_ENCRYPT=off\n");
    expect(await readFile(managed, "utf8")).toBe(GENERATED);
  });

  test("moves values byte for byte, never prints them, and follows backslash continuations", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(
      managed,
      GENERATED +
        "S3_SECRET=a&b$c;d \"q\" 'r'\nLONG=one\\\n  two\nTWO_SLASHES=x\\\\\nBETTER_AUTH_URL=https://dashboard.example.com\n",
    );
    const r = split(managed, local, ...OWNED);
    expect(r.out).not.toContain("a&b");
    expect(r.out).toContain("moved S3_SECRET");
    expect(r.out).toContain("moved LONG");
    expect(r.out).toContain("moved TWO_SLASHES");
    const text = await readFile(local, "utf8");
    expect(text).toContain("S3_SECRET=a&b$c;d \"q\" 'r'\n");
    expect(text).toContain("LONG=one\\\n  two\n");
    // An even number of trailing backslashes does not continue: the next owned key stayed behind.
    expect(text).toContain("TWO_SLASHES=x\\\\\n");
    expect(await readFile(managed, "utf8")).toContain("BETTER_AUTH_URL=https://dashboard.example.com\n");
    expect(text).not.toContain("BETTER_AUTH_URL");
  });

  test("keeps comments and blank lines, and moves a line that is not an assignment instead of losing it", async () => {
    const managed = join(dir, "control.env");
    const local = join(dir, "control.local.env");
    await writeFile(managed, "# top\n\n; also a comment\nSPROUTBOAT_BOOTSTRAP_TOKEN=t\nthis is not valid\n");
    const r = split(managed, local, ...OWNED);
    expect(r.out).toContain("moved <unrecognized line>");
    expect(await readFile(managed, "utf8")).toBe("# top\n\n; also a comment\nSPROUTBOAT_BOOTSTRAP_TOKEN=t\n");
    expect(await readFile(local, "utf8")).toContain("this is not valid\n");
  });

  test("rewrites the managed file in place, so its owner and mode stay", async () => {
    const managed = join(dir, "control.env");
    await writeFile(managed, GENERATED + "X=1\n");
    await chmod(managed, 0o640);
    split(managed, join(dir, "control.local.env"), ...OWNED);
    expect((await stat(managed)).mode & 0o777).toBe(0o640);
  });

  test("needs a managed file, a local file and at least one key", () => {
    expect(Bun.spawnSync(["bash", "infra/sb-envsplit", "a", "b"]).exitCode).not.toBe(0);
  });
});

// install.sh's own helpers, eval'd out of the script the way tests/install-mode.test.ts does.
const fns = ["val_env_op", "env_split", "ensure_local_env", "operator_env"];
const load = [
  `eval "$(sed -n '/^val_env() /p' install.sh)"`,
  ...fns.map((n) => `eval "$(sed -n '/^${n}()/,/^}/p' install.sh)"`),
].join("\n");

function installer(script: string) {
  const prelude = [
    "set -euo pipefail",
    `ETC=${dir}`,
    `ROOT=${process.cwd()}`,
    'say() { :; }; note() { echo "note: $*"; }; ok() { echo "ok: $*"; }; warn() { echo "warn: $*" >&2; }',
    'die() { echo "die: $*" >&2; exit 1; }',
    "chown() { :; }", // not root here
    load,
  ].join("\n");
  const r = Bun.spawnSync(["bash", "-c", `${prelude}\n${script}`], { env: { PATH: process.env.PATH ?? "" } });
  return { code: r.exitCode, out: r.stdout.toString(), err: r.stderr.toString() };
}

/** What install.sh does to control.env on an update, in the order it does it. */
const CONTROL_KEYS =
  "SPROUTBOAT_DATABASE_PATH SPROUTBOAT_ARTIFACTS_DIR SPROUTBOAT_DEPLOYMENTS_PATH SPROUTBOAT_BOOTSTRAP_USERNAME SPROUTBOAT_BOOTSTRAP_TOKEN SPROUTBOAT_ADMIN_EMAILS BETTER_AUTH_SECRET BETTER_AUTH_URL SPROUTBOAT_BACKUP_KEY_FILE GITHUB_CLIENT_ID GITHUB_CLIENT_SECRET";
const UPDATE_CONTROL = `
operator_env control root:sproutboat 0640 "limits" ${CONTROL_KEYS}
printf 'SPROUTBOAT_BOOTSTRAP_TOKEN=tok\\nBETTER_AUTH_SECRET=sec\\n' > "$ETC/control.env"
`;

describe("install.sh keeps operator settings across updates", () => {
  test("a fresh install gets an empty local file with a header, and the generated file next to it", async () => {
    const r = installer(UPDATE_CONTROL);
    expect(r.code, r.err).toBe(0);
    const local = await readFile(join(dir, "control.local.env"), "utf8");
    expect(local).toContain("install.sh never rewrites this file");
    expect(local.split("\n").every((l) => l === "" || l.startsWith("#"))).toBe(true);
    expect((await stat(join(dir, "control.local.env"))).mode & 0o777).toBe(0o640);
  });

  test("an old control.env with operator keys: the update moves them and they survive a second update", async () => {
    await writeFile(
      join(dir, "control.env"),
      [
        "SPROUTBOAT_DATABASE_PATH=/var/lib/sproutboat/sproutboat.sqlite",
        "SPROUTBOAT_BOOTSTRAP_TOKEN=tok",
        "BETTER_AUTH_SECRET=sec",
        "SPROUTBOAT_BACKUP_ENCRYPT=off",
        "SPROUTBOAT_BACKUP_S3_BUCKET=bk",
        "SPROUTBOAT_BACKUP_S3_SECRET_ACCESS_KEY=s3&secret",
        "SPROUTBOAT_DEPLOY_RATE_PER_MIN=30",
        "",
      ].join("\n"),
    );
    const first = installer(UPDATE_CONTROL);
    expect(first.code, first.err).toBe(0);
    expect(first.out).toContain("note: control.env: moved SPROUTBOAT_BACKUP_ENCRYPT to control.local.env");
    expect(first.out).toContain("ok: the old control.env is kept as");
    expect(first.out).not.toContain("s3&secret");

    const afterFirst = await readFile(join(dir, "control.local.env"), "utf8");
    for (const kv of [
      "SPROUTBOAT_BACKUP_ENCRYPT=off",
      "SPROUTBOAT_BACKUP_S3_BUCKET=bk",
      "SPROUTBOAT_BACKUP_S3_SECRET_ACCESS_KEY=s3&secret",
      "SPROUTBOAT_DEPLOY_RATE_PER_MIN=30",
    ]) {
      expect(afterFirst).toContain(`${kv}\n`);
    }
    // The generated file holds only generated keys.
    expect(await readFile(join(dir, "control.env"), "utf8")).toBe(
      "SPROUTBOAT_BOOTSTRAP_TOKEN=tok\nBETTER_AUTH_SECRET=sec\n",
    );

    // The second update has nothing to move and leaves the local file as it was.
    const second = installer(UPDATE_CONTROL);
    expect(second.code, second.err).toBe(0);
    expect(second.out).not.toContain("moved");
    expect(await readFile(join(dir, "control.local.env"), "utf8")).toBe(afterFirst);
    expect((await readdir(dir)).filter((f) => f.startsWith("control.env.bak-"))).toHaveLength(1);
  });

  test("keys an operator edits into the local file between updates are never touched", async () => {
    installer(UPDATE_CONTROL);
    const file = join(dir, "control.local.env");
    await writeFile(file, (await readFile(file, "utf8")) + "SPROUTBOAT_BACKUP_S3_BUCKET=mine\n");
    installer(UPDATE_CONTROL);
    installer(UPDATE_CONTROL);
    expect(await readFile(file, "utf8")).toContain("SPROUTBOAT_BACKUP_S3_BUCKET=mine\n");
  });

  test("SB_EGRESS_ALLOW in egress.env moves to egress.local.env, and the token stays where it is", async () => {
    await writeFile(join(dir, "egress.env"), "SB_EGRESS_TOKEN=tok\nSB_EGRESS_ALLOW=10.0.0.5\n");
    const r = installer(`operator_env egress root:root 0600 "allow" SB_EGRESS_TOKEN`);
    expect(r.code, r.err).toBe(0);
    expect(await readFile(join(dir, "egress.env"), "utf8")).toBe("SB_EGRESS_TOKEN=tok\n");
    expect(await readFile(join(dir, "egress.local.env"), "utf8")).toContain("SB_EGRESS_ALLOW=10.0.0.5\n");
  });

  test("val_env_op prefers the local file, then the generated one", async () => {
    await writeFile(join(dir, "control.env"), "SPROUTBOAT_BACKUP_KEY_FILE=/etc/sproutboat/backup.key\nOTHER=1\n");
    await writeFile(join(dir, "control.local.env"), "SPROUTBOAT_BACKUP_KEY_FILE=/mnt/keys/backup.key\n");
    const both = installer(`val_env_op "$ETC/control.env" "$ETC/control.local.env" SPROUTBOAT_BACKUP_KEY_FILE`);
    expect(both.out).toBe("/mnt/keys/backup.key");
    const onlyManaged = installer(`val_env_op "$ETC/control.env" "$ETC/none.env" OTHER`);
    expect(onlyManaged.out).toBe("1");
    const neither = installer(`val_env_op "$ETC/none.env" "$ETC/none2.env" OTHER`);
    expect(neither.out).toBe("");
  });
});

describe("the managed key lists match what install.sh writes", () => {
  // If install.sh starts writing a key to control.env and forgets the list, the first update after
  // that would move the key into the local file, where it would shadow the generated value forever.
  for (const name of ["sproutboat", "control", "egress", "caddy"]) {
    test(`${name}.env`, async () => {
      const install = await Bun.file("install.sh").text();
      // The generated block: from the "{" line before it to the "} > file" line.
      const close = install.indexOf(`} > "$ETC/${name}.env"`);
      expect(close, `no generated block for ${name}.env`).toBeGreaterThan(0);
      const block = install.slice(install.lastIndexOf("\n{\n", close), close);
      const written = [...block.matchAll(/echo "([A-Z][A-Z0-9_]*)=/g)].map((m) => m[1]);
      expect(written.length).toBeGreaterThan(0);
      // The operator_env call: its line and the continuation lines that follow.
      const at = install.indexOf(`operator_env ${name} `);
      expect(at, `no operator_env call for ${name}`).toBeGreaterThan(0);
      const lines = install.slice(at).split("\n");
      let call = "";
      for (const line of lines) {
        call += line + "\n";
        if (!line.endsWith("\\")) break;
      }
      // The managed keys are the words after the quoted description.
      const keys = call.slice(call.indexOf('" ') + 1).match(/\b[A-Z][A-Z0-9_]+\b/g) ?? [];
      for (const key of written)
        expect(keys, `${key} is written to ${name}.env but not in its managed list`).toContain(key);
      for (const key of keys)
        expect(written, `${key} is listed as managed but install.sh never writes it`).toContain(key);
    });
  }
});

describe("the units and tools read the local files", () => {
  const read = (f: string) => Bun.file(f).text();
  const order = (text: string, a: string, b: string) => {
    expect(text, a).toContain(a);
    expect(text, b).toContain(b);
    expect(text.indexOf(a)).toBeLessThan(text.indexOf(b));
  };

  test("each unit reads <name>.local.env right after <name>.env, as an optional file", async () => {
    const control = await read("infra/systemd/sproutboat-control.service");
    order(
      control,
      "EnvironmentFile=-/etc/sproutboat/sproutboat.env",
      "EnvironmentFile=-/etc/sproutboat/sproutboat.local.env",
    );
    order(
      control,
      "EnvironmentFile=-/etc/sproutboat/control.env",
      "EnvironmentFile=-/etc/sproutboat/control.local.env",
    );
    order(control, "EnvironmentFile=-/etc/sproutboat/egress.env", "EnvironmentFile=-/etc/sproutboat/egress.local.env");
    // The local control settings win over the egress file too.
    const edge = await read("infra/systemd/sproutboat-edge.service");
    order(
      edge,
      "EnvironmentFile=-/etc/sproutboat/sproutboat.env",
      "EnvironmentFile=-/etc/sproutboat/sproutboat.local.env",
    );
    order(edge, "EnvironmentFile=-/etc/sproutboat/egress.env", "EnvironmentFile=-/etc/sproutboat/egress.local.env");
    const egress = await read("infra/systemd/sproutboat-egress.service");
    order(egress, "EnvironmentFile=/etc/sproutboat/egress.env", "EnvironmentFile=-/etc/sproutboat/egress.local.env");
  });

  test("the backup unit reads control.local.env: S3 and encryption settings live there", async () => {
    const backup = await read("infra/systemd/sproutboat-backup.service");
    order(backup, "EnvironmentFile=-/etc/sproutboat/control.env", "EnvironmentFile=-/etc/sproutboat/control.local.env");
  });

  test("the Caddy drop-in reads caddy.local.env after caddy.env", async () => {
    const install = await read("install.sh");
    order(install, "EnvironmentFile=$ETC/caddy.env", "EnvironmentFile=-$ETC/caddy.local.env");
  });

  test("install.sh settles all four local files before it rewrites the generated ones", async () => {
    const install = await read("install.sh");
    for (const name of ["sproutboat", "control", "egress", "caddy"]) {
      const call = install.indexOf(`operator_env ${name} `);
      expect(call, name).toBeGreaterThan(0);
      expect(call, name).toBeLessThan(install.indexOf(`} > "$ETC/${name}.env"`));
    }
    // The pre-update backup verifier reads the key file path the way the backup unit does.
    expect(install).toContain('val_env_op "$ETC/control.env" "$ETC/control.local.env" SPROUTBOAT_BACKUP_KEY_FILE');
    // The installer no longer writes the operator's egress allow list back by itself.
    expect(install).not.toContain('echo "SB_EGRESS_ALLOW=$EGRESS_ALLOW"');
    // GitHub sign-in survives an update that is not given the OAuth app again.
    expect(install).toContain('val_env "$ETC/control.env" GITHUB_CLIENT_ID');
    expect(install).toContain('val_env "$ETC/control.env" GITHUB_CLIENT_SECRET');
  });

  test("restore and rollback give the local files the owner and mode of their generated twin", async () => {
    for (const f of ["infra/sbctl", "infra/sb-rollback"]) {
      const text = await read(f);
      expect(text, f).toContain("control.env control.local.env sproutboat.env sproutboat.local.env backup.key");
      expect(text, f).toContain("caddy.env caddy.local.env");
      expect(text, f).toContain("egress.env egress.local.env update.env");
    }
  });

  test("sbctl parses the env files instead of sourcing them", async () => {
    const sbctl = await read("infra/sbctl");
    expect(sbctl).not.toMatch(/^\s*\. "\$ETC\/(control|sproutboat)\.env"/m);
    expect(sbctl).toContain("load_control_env");
    expect(sbctl).toContain('"$ETC/control.env" "$ETC/control.local.env"');
  });
});

describe("sbctl load_env", () => {
  function loadEnv(files: Record<string, string>, show: string) {
    return (async () => {
      const paths: string[] = [];
      for (const [name, text] of Object.entries(files)) {
        await writeFile(join(dir, name), text);
        paths.push(join(dir, name));
      }
      paths.push(join(dir, "missing.env"));
      const script = [
        "set -euo pipefail",
        `eval "$(sed -n '/^load_env()/,/^}/p' infra/sbctl)"`,
        `load_env ${paths.map((p) => `'${p}'`).join(" ")}`,
        show,
      ].join("\n");
      const r = Bun.spawnSync(["bash", "-c", script], { env: { PATH: process.env.PATH ?? "" } });
      return { code: r.exitCode, out: r.stdout.toString(), err: r.stderr.toString() };
    })();
  }

  test("reads values with shell metacharacters as data, and never runs them", async () => {
    const marker = join(dir, "ran");
    const r = await loadEnv(
      { "a.env": `SECRET=ab&cd$ef;touch ${marker}\nBACKTICK=\`touch ${marker}\`\nSUB=$(touch ${marker})\n` },
      'printf "%s|%s|%s" "$SECRET" "$BACKTICK" "$SUB"',
    );
    expect(r.code, r.err).toBe(0);
    expect(r.out).toBe(`ab&cd$ef;touch ${marker}|\`touch ${marker}\`|$(touch ${marker})`);
    expect(existsSync(marker)).toBe(false);
  });

  test("later files and later lines win, one pair of quotes is stripped, comments and junk are skipped", async () => {
    const r = await loadEnv(
      {
        "a.env": "# c\nX=1\nX=2\nQ=\"two words\"\nS='single'\nnot an assignment\n9BAD=1\nEMPTY=\n",
        "b.env": "X=3\n",
      },
      'printf "%s|%s|%s|%s|[%s]" "$X" "$Q" "$S" "$(printenv 9BAD || echo none)" "${EMPTY-unset}"',
    );
    expect(r.out).toBe("3|two words|single|none|[]");
  });
});
